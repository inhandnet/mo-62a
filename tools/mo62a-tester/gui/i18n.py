def set_lang(lang: str) -> None:
    global _LANG
    if lang in _STRINGS:
        _LANG = lang


def get_lang() -> str:
    return _LANG


def t(key: str, *args) -> str:
    """返回当前语言的翻译字符串，支持 .format() 占位符。"""
    s = _STRINGS.get(_LANG, _STRINGS["en"]).get(key, key)
    if args:
        return s.format(*args)
    return s
